            {
                var instruction = instructions[random.Next(instructions.Length)];
                var reg1 = registers[random.Next(registers.Length)];
                var reg2 = registers[random.Next(registers.Length)];
                assembly.AppendLine($"    {instruction} {reg1}, {reg2}");
            }
            
            return assembly.ToString();
        }

        private async Task CrossPatch(string source, string target, string assembly)
        {
            Console.WriteLine($"Cross-patch: {source} -> {target}");
            
