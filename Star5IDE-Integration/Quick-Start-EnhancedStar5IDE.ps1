            var fileName = $"{source}_to_{target}_{DateTime.UtcNow:yyyyMMdd_HHmmss}.asm";
            await UploadToOceanDigital(fileName, Encoding.UTF8.GetBytes(assembly));
            
            // Commit to GitHub
            await CommitToGitHub(fileName, assembly);
        }

        private async Task StartOceanDigitalIntegration()
