                    Console.WriteLine($"GitHub error: {ex.Message}");
                }
            }
        }

        private async Task UploadToOceanDigital(string fileName, byte[] data)
        {
            try
            {
                var content = new ByteArrayContent(data);
                var response = await _httpClient.PutAsync($"https://star5ide-assembly.nyc3.digitaloceanspaces.com/{fileName}", content);
                
                if (response.IsSuccessStatusCode)
                {
                    Console.WriteLine($"Uploaded to Ocean Digital: {fileName}");
                }
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Ocean Digital upload failed: {ex.Message}");
            }
        }

        private async Task CommitToGitHub(string fileName, string content)
        {
            try
            {
                // Create file in repository
                var filePath = $"generated/{fileName}";
                File.WriteAllText(filePath, content);
                
                // Git operations
                var gitAdd = System.Diagnostics.Process.Start("git", $"add {filePath}");
                gitAdd.WaitForExit();
                
                var gitCommit = System.Diagnostics.Process.Start("git", $"commit -m \"Generated assembly: {fileName}\"");
                gitCommit.WaitForExit();
                
                var gitPush = System.Diagnostics.Process.Start("git", "push origin main");
                gitPush.WaitForExit();
                
                Console.WriteLine($"Committed to GitHub: {fileName}");
            }
            catch (Exception ex)
            {
                Console.WriteLine($"GitHub commit failed: {ex.Message}");
            }
        }
    }
