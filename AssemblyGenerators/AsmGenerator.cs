using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace AssemblyGenerators
{
    public class AsmGenerator
    {
        private readonly Random _random;
        private readonly List<string> _carMarkers;
        private readonly Dictionary<string, string> _instructionTemplates;
        private readonly PanelIntegration.PanelConnector _panelConnector;

        public string Name { get; private set; }
        public string TargetArchitecture { get; private set; }
        public List<string> GeneratedInstructions { get; private set; }
        public Dictionary<string, IntPtr> HotPatchMarkers { get; private set; }

        public AsmGenerator(string name, string targetArch, PanelIntegration.PanelConnector panelConnector = null)
        {
            Name = name;
            TargetArchitecture = targetArch;
            _random = new Random();
            _panelConnector = panelConnector;
            _carMarkers = new List<string>();
            GeneratedInstructions = new List<string>();
            HotPatchMarkers = new Dictionary<string, IntPtr>();

            InitializeInstructionTemplates();
            GenerateCarMarkers();
        }

        private void InitializeInstructionTemplates()
        {
            _instructionTemplates = new Dictionary<string, string>
            {
                // x64 Instructions
                ["mov"] = "mov {0}, {1}",
                ["add"] = "add {0}, {1}",
                ["sub"] = "sub {0}, {1}",
                ["xor"] = "xor {0}, {1}",
                ["and"] = "and {0}, {1}",
                ["or"] = "or {0}, {1}",
                ["shl"] = "shl {0}, {1}",
                ["shr"] = "shr {0}, {1}",
                ["rol"] = "rol {0}, {1}",
                ["ror"] = "ror {0}, {1}",
                ["lea"] = "lea {0}, {1}",
                ["call"] = "call {0}",
                ["jmp"] = "jmp {0}",
                ["je"] = "je {0}",
                ["jne"] = "jne {0}",
                ["jz"] = "jz {0}",
                ["jnz"] = "jnz {0}",
                ["push"] = "push {0}",
                ["pop"] = "pop {0}",
                ["ret"] = "ret",
                ["nop"] = "nop",
                ["int3"] = "int3",
                ["syscall"] = "syscall"
            };
        }

        private void GenerateCarMarkers()
        {
            for (int i = 1; i <= 10; i++)
            {
                _carMarkers.Add($"car_marker_{i}");
            }
        }

        public async Task<string> GenerateAssembly(int instructionCount = 100)
        {
            var assembly = new StringBuilder();
            
            // Assembly header
            assembly.AppendLine($"; Generated by {Name} for {TargetArchitecture}");
            assembly.AppendLine($"; Timestamp: {DateTime.UtcNow:yyyy-MM-dd HH:mm:ss}");
            assembly.AppendLine($"; Instruction Count: {instructionCount}");
            assembly.AppendLine();

            // Add car markers as assembly labels
            foreach (var marker in _carMarkers)
            {
                assembly.AppendLine($"{marker}:");
                assembly.AppendLine("    ; Hot patch point");
                assembly.AppendLine();
            }

            // Generate random instructions
            var instructions = GenerateRandomInstructions(instructionCount);
            GeneratedInstructions = instructions;

            foreach (var instruction in instructions)
            {
                assembly.AppendLine($"    {instruction}");
            }

            // Assembly footer
            assembly.AppendLine();
            assembly.AppendLine("; End of generated assembly");

            // Send to panel
            if (_panelConnector != null)
            {
                var features = new Dictionary<string, object>
                {
                    ["car_markers"] = _carMarkers.Count,
                    ["instruction_templates"] = _instructionTemplates.Count,
                    ["random_seed"] = _random.Next()
                };

                await _panelConnector.SendAssemblyGeneration(Name, TargetArchitecture, instructionCount, features);
            }

            return assembly.ToString();
        }

        private List<string> GenerateRandomInstructions(int count)
        {
            var instructions = new List<string>();
            var registers = GetRegisters();
            var instructionNames = _instructionTemplates.Keys.ToList();

            for (int i = 0; i < count; i++)
            {
                var instructionName = instructionNames[_random.Next(instructionNames.Count)];
                var template = _instructionTemplates[instructionName];

                // Skip instructions that don't take operands
                if (instructionName == "ret" || instructionName == "nop" || instructionName == "int3" || instructionName == "syscall")
                {
                    instructions.Add(instructionName);
                    continue;
                }

                // Generate operands
                var operand1 = GenerateOperand(registers);
                var operand2 = GenerateOperand(registers);

                try
                {
                    var instruction = string.Format(template, operand1, operand2);
                    instructions.Add(instruction);
                }
                catch
                {
                    // Fallback to simple instruction
                    instructions.Add(instructionName);
                }
            }

            return instructions;
        }

        private string GenerateOperand(List<string> registers)
        {
            var operandTypes = new[] { "register", "immediate", "memory" };
            var type = operandTypes[_random.Next(operandTypes.Length)];

            switch (type)
            {
                case "register":
                    return registers[_random.Next(registers.Count)];

                case "immediate":
                    return $"0x{_random.Next(0x1000):X}";

                case "memory":
                    var reg = registers[_random.Next(registers.Count)];
                    var offset = _random.Next(-0x100, 0x100);
                    return $"[{reg}{(offset >= 0 ? "+" : "")}{offset}]";

                default:
                    return registers[_random.Next(registers.Count)];
            }
        }

        private List<string> GetRegisters()
        {
            return TargetArchitecture.ToLower() switch
            {
                "x64" => new List<string> { "rax", "rbx", "rcx", "rdx", "rsi", "rdi", "rsp", "rbp", "r8", "r9", "r10", "r11", "r12", "r13", "r14", "r15" },
                "x86" => new List<string> { "eax", "ebx", "ecx", "edx", "esi", "edi", "esp", "ebp" },
                "arm64" => new List<string> { "x0", "x1", "x2", "x3", "x4", "x5", "x6", "x7", "x8", "x9", "x10", "x11", "x12", "x13", "x14", "x15" },
                _ => new List<string> { "rax", "rbx", "rcx", "rdx", "rsi", "rdi", "rsp", "rbp" }
            };
        }

        public async Task<byte[]> CompileAssembly(string assemblyCode)
        {
            var tempAsmFile = Path.GetTempFileName() + ".asm";
            var tempObjFile = Path.GetTempFileName() + ".obj";
            var tempExeFile = Path.GetTempFileName() + ".exe";

            try
            {
                // Write assembly to file
                await File.WriteAllTextAsync(tempAsmFile, assemblyCode);

                // Compile with NASM/YASM (if available)
                var compileResult = await CompileWithNasm(tempAsmFile, tempObjFile);
                if (!compileResult)
                {
                    // Fallback to generating machine code directly
                    return GenerateMachineCode(assemblyCode);
                }

                // Link to create executable
                var linkResult = await LinkObjectFile(tempObjFile, tempExeFile);
                if (linkResult && File.Exists(tempExeFile))
                {
                    return await File.ReadAllBytesAsync(tempExeFile);
                }

                return GenerateMachineCode(assemblyCode);
            }
            finally
            {
                // Clean up temporary files
                if (File.Exists(tempAsmFile)) File.Delete(tempAsmFile);
                if (File.Exists(tempObjFile)) File.Delete(tempObjFile);
                if (File.Exists(tempExeFile)) File.Delete(tempExeFile);
            }
        }

        private async Task<bool> CompileWithNasm(string asmFile, string objFile)
        {
            try
            {
                var startInfo = new System.Diagnostics.ProcessStartInfo
                {
                    FileName = "nasm",
                    Arguments = $"-f win64 -o \"{objFile}\" \"{asmFile}\"",
                    RedirectStandardOutput = true,
                    RedirectStandardError = true,
                    UseShellExecute = false,
                    CreateNoWindow = true
                };

                using var process = System.Diagnostics.Process.Start(startInfo);
                await process.WaitForExitAsync();
                return process.ExitCode == 0;
            }
            catch
            {
                return false;
            }
        }

        private async Task<bool> LinkObjectFile(string objFile, string exeFile)
        {
            try
            {
                var startInfo = new System.Diagnostics.ProcessStartInfo
                {
                    FileName = "link",
                    Arguments = $"/SUBSYSTEM:CONSOLE /ENTRY:main \"{objFile}\" /OUT:\"{exeFile}\"",
                    RedirectStandardOutput = true,
                    RedirectStandardError = true,
                    UseShellExecute = false,
                    CreateNoWindow = true
                };

                using var process = System.Diagnostics.Process.Start(startInfo);
                await process.WaitForExitAsync();
                return process.ExitCode == 0;
            }
            catch
            {
                return false;
            }
        }

        private byte[] GenerateMachineCode(string assemblyCode)
        {
            // Simple machine code generation for common instructions
            var machineCode = new List<byte>();
            var lines = assemblyCode.Split('\n', StringSplitOptions.RemoveEmptyEntries);

            foreach (var line in lines)
            {
                var trimmedLine = line.Trim();
                if (string.IsNullOrEmpty(trimmedLine) || trimmedLine.StartsWith(";"))
                    continue;

                // Generate random machine code bytes for each instruction
                var instructionBytes = GenerateRandomMachineCode();
                machineCode.AddRange(instructionBytes);
            }

            return machineCode.ToArray();
        }

        private byte[] GenerateRandomMachineCode()
        {
            // Generate 1-15 random bytes per instruction
            var length = _random.Next(1, 16);
            var bytes = new byte[length];
            _random.NextBytes(bytes);
            return bytes;
        }

        public void RegisterHotPatchMarker(string markerName, IntPtr address)
        {
            HotPatchMarkers[markerName] = address;
        }

        public async Task<bool> ApplyHotPatch(string patchName, string targetMarker, byte[] patchData)
        {
            if (!HotPatchMarkers.ContainsKey(targetMarker))
            {
                Console.WriteLine($"Marker {targetMarker} not found");
                return false;
            }

            var markerAddress = HotPatchMarkers[targetMarker];
            
            try
            {
                // Apply patch using VirtualProtect
                if (VirtualProtect(markerAddress, (uint)patchData.Length, 0x40, out uint oldProtect))
                {
                    System.Runtime.InteropServices.Marshal.Copy(patchData, 0, markerAddress, patchData.Length);
                    FlushInstructionCache(System.Diagnostics.Process.GetCurrentProcess().Handle, markerAddress, (uint)patchData.Length);
                    VirtualProtect(markerAddress, (uint)patchData.Length, oldProtect, out _);

                    // Send to panel
                    if (_panelConnector != null)
                    {
                        var details = new Dictionary<string, object>
                        {
                            ["patch_size"] = patchData.Length,
                            ["target_address"] = markerAddress.ToString("X"),
                            ["generator_name"] = Name
                        };

                        await _panelConnector.SendHotPatchEvent(patchName, targetMarker, true, details);
                    }

                    return true;
                }
            }
            catch (Exception ex)
            {
                Console.WriteLine($"Failed to apply hot patch: {ex.Message}");
                
                if (_panelConnector != null)
                {
                    var details = new Dictionary<string, object>
                    {
                        ["error"] = ex.Message,
                        ["generator_name"] = Name
                    };

                    await _panelConnector.SendHotPatchEvent(patchName, targetMarker, false, details);
                }
            }

            return false;
        }

        // P/Invoke declarations
        [System.Runtime.InteropServices.DllImport("kernel32.dll", SetLastError = true)]
        private static extern bool VirtualProtect(IntPtr lpAddress, uint dwSize, uint flNewProtect, out uint lpflOldProtect);

        [System.Runtime.InteropServices.DllImport("kernel32.dll", SetLastError = true)]
        private static extern bool FlushInstructionCache(IntPtr hProcess, IntPtr lpBaseAddress, uint dwSize);
    }
}